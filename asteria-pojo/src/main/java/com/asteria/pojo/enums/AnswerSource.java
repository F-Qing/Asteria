package com.asteria.pojo.enums;

/**
 * 答案的来源 —— 也就是这道题的答案"是谁写的"。
 *
 * <p>为什么需要区分：AI 补出来的答案和原文里带的答案，**可信度不一样**。
 * 如果不记录来源，AI 会直接覆盖掉原答案，而你又无从追溯 ——
 * 将来想做"人工复核 AI 补的答案"或者"把 AI 改的答案全部回滚"，
 * 会发现原始数据已经没了，什么都做不了。
 *
 * <p>这叫**数据血缘**（data lineage）：知道每份数据从哪来、被谁改过。
 */
public enum AnswerSource {

    /** 从上传的文件里解析出来的（可信度最高） */
    FILE,

    /** 文件里没有答案，模型自己解出来的 */
    AI,

    /** 人工改过的（预留给将来的校对功能） */
    MANUAL
}
